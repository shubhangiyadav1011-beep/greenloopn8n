import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve, dirname, basename } from 'node:path';
import { createBackend } from './databaseHarness.mjs';

test('passport and request CRUD preserves ownership, order commitments and deleted record identities', async () => {
  const directory = mkdtempSync(join(tmpdir(), 'greenloop-crud-'));
  let server = createBackend({ dataDir: directory });
  let base;
  const listen = async () => { await new Promise(resolve => server.listen(0, '127.0.0.1', resolve)); base = `http://127.0.0.1:${server.address().port}`; };
  const client = () => {
    let cookie = '';
    return async (path, method = 'GET', data, expected = 200) => {
      const response = await fetch(`${base}/api${path}`, { method, headers: { 'Content-Type': 'application/json', 'X-GreenLoop-Client': 'web', Cookie: cookie }, body: data === undefined ? undefined : JSON.stringify(data) });
      if (response.headers.get('set-cookie')) cookie = response.headers.get('set-cookie').split(';')[0];
      const result = await response.json();
      assert.equal(response.status, expected, JSON.stringify(result)); return result;
    };
  };
  const provider = client(); const receiver = client(); const outsider = client();
  const act = (request, action, args, expected = 200) => request('/actions', 'POST', { action, args }, expected);
  const day = offset => new Date(Date.now() + offset * 86400000).toISOString().slice(0, 10);
  try {
    await listen();
    await provider('/auth/register', 'POST', { email: 'crud-provider@example.com', password: 'password123', organization: 'Builder' }, 201);
    await provider('/profile', 'PATCH', { workspaces: ['provider'], activeWorkspace: 'provider' });
    await receiver('/auth/register', 'POST', { email: 'crud-receiver@example.com', password: 'password123', organization: 'Yard' }, 201);
    const facility = (await receiver('/profile', 'PATCH', { workspaces: ['receiver'], activeWorkspace: 'receiver', location: 'Delhi' })).user.receiverId;
    await outsider('/auth/register', 'POST', { email: 'crud-outsider@example.com', password: 'password123' }, 201);
    await outsider('/profile', 'PATCH', { workspaces: ['provider', 'receiver'], activeWorkspace: 'provider' });
    const project = (await act(provider, 'addProjectAction', [{ name: 'Project', location: 'Delhi', status: 'active' }])).result;
    const createMaterial = () => act(provider, 'addMaterialAction', [{ projectId: project.id, type: 'concrete', quantityT: 10, quantityRangeT: [8, 12], condition: 'good', grade: 'A', confidence: 0.9, evidence: [] }]);
    const material = (await createMaterial()).result;
    const editMaterial = { type: 'concrete', quantityT: 12, condition: 'fair', grade: 'B', surveyNotes: 'Updated notes', pricePerT: 500, availableFrom: day(1) };
    await act(outsider, 'updateMaterialAction', [material.id, editMaterial], 403);
    await act(receiver, 'deleteMaterialAction', [material.id], 403);
    await act(provider, 'updateMaterialAction', [material.id, { ...editMaterial, quantityT: -1 }], 400);
    await act(provider, 'updateMaterialAction', [material.id, { ...editMaterial, status: 'verified', projectId: 'fake' }]);
    const changedMaterial = (await provider('/dataset')).dataset.materials.find(item => item.id === material.id);
    assert.equal(changedMaterial.projectId, project.id);
    assert.notEqual(changedMaterial.status, 'verified');
    assert.equal(changedMaterial.quantityT, 12);
    assert.equal((await receiver('/dataset')).dataset.providerListings.find(item => item.materialId === material.id).pricePerT, 500);

    const directedInput = { materialType: 'concrete', requiredT: 2, period: day(7), location: 'Delhi', targetMaterialId: material.id, targetProviderId: 'spoofed@example.com' };
    const direct = (await act(receiver, 'addDemandAction', [directedInput])).result;
    assert.equal(direct.targetMaterialId, material.id);
    assert.equal(direct.targetProviderId, 'crud-provider@example.com');
    assert.equal(direct.targetProviderName, 'Builder');
    const providerView = (await provider('/dataset')).dataset;
    assert.ok(providerView.demands.some(item => item.id === direct.id));
    assert.ok(providerView.events.some(item => item.kind === 'demand.created' && item.subjectIds.includes(direct.id)));
    assert.equal((await outsider('/dataset')).dataset.demands.some(item => item.id === direct.id), false);
    await act(receiver, 'addDemandAction', [{ ...directedInput, targetMaterialId: 'missing' }], 409);
    await act(receiver, 'addDemandAction', [{ ...directedInput, materialType: 'brick' }], 409);
    await act(receiver, 'addDemandAction', [{ ...directedInput, requiredT: 13 }], 409);
    await act(receiver, 'saveDemandDraftAction', [{ ...directedInput, period: day(0) }], 409);
    const otherProject = (await act(outsider, 'addProjectAction', [{ name: 'Other', location: 'Delhi', status: 'active' }])).result;
    const otherMaterial = (await act(outsider, 'addMaterialAction', [{ projectId: otherProject.id, type: 'concrete', quantityT: 10, quantityRangeT: [8, 12], condition: 'good', grade: 'A', confidence: 0.9, evidence: [] }])).result;
    await act(outsider, 'addOfferAction', [{ demandId: direct.id, passportId: otherMaterial.id, offeredQuantityT: 2 }], 403);
    await act(outsider, 'saveOfferDraftAction', [{ demandId: direct.id, passportId: otherMaterial.id, offeredQuantityT: 2 }], 403);
    const differentMaterial = (await createMaterial()).result;
    await act(provider, 'addOfferAction', [{ demandId: direct.id, passportId: differentMaterial.id, offeredQuantityT: 2 }], 403);
    await act(provider, 'addOfferAction', [{ demandId: direct.id, passportId: material.id, offeredQuantityT: 2 }]);
    assert.ok((await receiver('/dataset')).dataset.offers.some(item => item.demandId === direct.id && item.passportId === material.id));

    const request = (await act(receiver, 'addDemandAction', [{ materialType: 'concrete', requiredT: 8, period: day(7), location: 'Delhi' }])).result;
    const editRequest = { materialType: 'concrete', requiredT: 10, period: day(14), location: 'Delhi', notes: 'More material needed', budgetPerT: 700 };
    await act(outsider, 'updateDemandAction', [request.id, editRequest], 403);
    await act(provider, 'deleteDemandAction', [request.id], 403);
    await act(receiver, 'updateDemandAction', [request.id, { ...editRequest, period: day(-1) }], 400);
    await act(receiver, 'updateDemandAction', [request.id, editRequest]);
    assert.equal((await provider('/dataset')).dataset.demands.find(item => item.id === request.id).requiredT, 10);
    const offer = (await act(provider, 'addOfferAction', [{ passportId: material.id, demandId: request.id, offeredQuantityT: 8, pricePerT: 500 }])).dataset.offers.find(item => item.demandId === request.id);
    await act(receiver, 'updateDemandAction', [request.id, { ...editRequest, materialType: 'brick' }], 409);
    await act(provider, 'updateMaterialAction', [material.id, { ...editMaterial, grade: 'C' }], 409);
    const slot = (await act(receiver, 'addCapacityAction', [{ receiverId: facility, date: day(7), materialType: 'concrete', capacityT: 10 }])).result;
    const proposal = (await act(provider, 'proposeFinalTermsAction', [offer.id, { quantityT: 8, pricePerT: 500, destination: 'Delhi', slotId: slot.id }])).result;
    await act(receiver, 'approveFinalTermsAction', [offer.id, proposal.id]);
    await act(provider, 'updateMaterialAction', [material.id, editMaterial], 409);
    await act(provider, 'deleteMaterialAction', [material.id], 409);
    await act(receiver, 'deleteDemandAction', [request.id], 409);
    await act(receiver, 'updateDemandAction', [request.id, { ...editRequest, requiredT: 7 }], 409);
    await act(receiver, 'updateDemandAction', [request.id, { ...editRequest, period: day(1) }], 409);
    await act(receiver, 'updateDemandAction', [request.id, { ...editRequest, location: 'Elsewhere' }], 409);
    await act(receiver, 'updateDemandAction', [request.id, { ...editRequest, requiredT: 12 }]);

    const spare = (await createMaterial()).result;
    const extra = (await act(receiver, 'addDemandAction', [{ materialType: 'concrete', requiredT: 2, period: day(7), location: 'Delhi' }])).result;
    const extraOffer = (await act(provider, 'addOfferAction', [{ passportId: spare.id, demandId: extra.id, offeredQuantityT: 2 }])).dataset.offers.find(item => item.demandId === extra.id);
    await act(receiver, 'deleteDemandAction', [extra.id]);
    assert.equal((await provider('/dataset')).dataset.demands.some(item => item.id === extra.id), false);
    assert.equal((await provider('/dataset')).dataset.offers.some(item => item.id === extraOffer.id), false);
    await act(receiver, 'deleteDemandAction', [extra.id], 404);
    await act(provider, 'addOfferAction', [{ passportId: spare.id, demandId: extra.id, offeredQuantityT: 1 }], 409);
    const replacement = (await act(receiver, 'addDemandAction', [{ materialType: 'concrete', requiredT: 2, period: day(7), location: 'Delhi' }])).result;
    assert.notEqual(replacement.id, extra.id);
    const pending = (await act(provider, 'addOfferAction', [{ passportId: spare.id, demandId: replacement.id, offeredQuantityT: 2 }])).dataset.offers.find(item => item.demandId === replacement.id);
    assert.notEqual(pending.id, extraOffer.id);
    await act(provider, 'deleteMaterialAction', [spare.id]);
    assert.equal((await receiver('/dataset')).dataset.providerListings.some(item => item.materialId === spare.id), false);
    assert.equal((await receiver('/dataset')).dataset.offers.some(item => item.id === pending.id), false);
    await act(provider, 'updateMaterialAction', [spare.id, editMaterial], 404);
    assert.notEqual((await createMaterial()).result.id, spare.id);
    await new Promise(resolve => server.close(resolve));
    server = createBackend({ dataDir: directory }); await listen();
    const persisted = (await receiver('/dataset')).dataset;
    assert.equal(persisted.demands.find(item => item.id === direct.id).targetMaterialId, material.id);
    assert.equal(persisted.demands.find(item => item.id === direct.id).targetProviderName, 'Builder');
    assert.equal(persisted.demands.find(item => item.id === request.id).requiredT, 12);
    assert.equal(persisted.demands.some(item => item.id === extra.id), false);
    assert.ok(persisted.events.some(event => event.kind === 'demand.deleted' && event.subjectIds.includes(extra.id)));
    assert.equal((await provider('/dataset')).dataset.materials.some(item => item.id === spare.id), false);
  } finally {
    await new Promise(resolve => server.close(resolve));
    const cleanupPath = resolve(directory);
    assert.equal(dirname(cleanupPath), resolve(tmpdir()));
    assert.ok(basename(cleanupPath).startsWith('greenloop-crud-'));
    rmSync(cleanupPath, { recursive: true, force: true });
  }
});
